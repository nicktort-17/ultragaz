# Имена узлов — те, что читает игра (P3_body/core/dome/halo/cables/wing0..5/scr0..5/podL/R/pmL/R/canL/R/cmL/R/hip0..7/knee0..7/seat).

def spike_cone(acc, base, d, L, r, mat='metal', n=5, local=False):
    d = V(d).normalized(); q = V((0, 0, 1)).rotation_difference(d).to_matrix().to_4x4()
    acc.add(cyl(r, 0, L, n), mat, Matrix.Translation(V(base) + d * L / 2) @ q, local=local)


