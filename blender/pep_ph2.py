# Силуэт: огромные скошенные наплечники-«капоты» (кремовый колпак, красные косые решётки спереди и сзади),
# V-образная грудь с решёткой из трёх красных планок, кремовый воротник-«ярмо» и лацканы, узкая талия,
# длинное красное знамя, кремовые набедренники, громадные кремовые наручи с косыми прорезями, когтистые кисти,
# синие бёдра, кремовые наколенники-«короны», голени с красной щелью, массивные кремовые щитки голеностопа.
# Из воротника торчит длинная жилистая шея; голова хоста садится на P2_seat (в игре — только голова с челюстью).
# Исполняется из pepsstein.py (exec) и переопределяет build_ph2(). Имена шарниров — те, что читает игра.

def seg_m(a, b, xh=(1, 0, 0)):
    """Рамка отрезка a→b: локальная Z вдоль a→b (нижнюю точку передавать первой — тогда Z смотрит вверх),
    X — как можно ближе к xh, начало в середине. Возвращает (M, длина)."""
    a = V(a); b = V(b); z = (b - a); L = z.length; z = z / L
    x = V(xh); x = x - z * x.dot(z)
    if x.length < 1e-4: x = V((0, 1, 0)) - z * z.y
    x.normalize(); y = z.cross(x)
    M = Matrix(((x.x, y.x, z.x, 0), (x.y, y.y, z.y, 0), (x.z, y.z, z.z, 0), (0, 0, 0, 1)))
    M.translation = (a + b) / 2
    return M, L


def tbox(a, b, s0, s1, xh=(1, 0, 0), cut=.24, sh0=(0, 0), sh1=(0, 0)):
    """Гранёный брус от a к b: полуразмеры сечения s0 у a и s1 у b (по локальным X,Y), срезанные углы, сдвиги сечений."""
    M, L = seg_m(a, b, xh); P = []
    for (hx, hy), (ox, oy), z in ((s0, sh0, -L / 2), (s1, sh1, L / 2)):
        for i in (-1, 1):
            for j in (-1, 1):
                P.append((ox + i * hx * (1 - cut), oy + j * hy, z)); P.append((ox + i * hx, oy + j * hy * (1 - cut), z))
    return hull(P), M


def hl(pts):
    return hull([tuple(p) for p in pts])


def mir(pts, s):
    return [(s * x, y, z) for x, y, z in pts]


def bars(acc, M, n, w, h, gap, slant, d=.06, mat='glow'):
    """n косых светящихся планок-параллелограммов в плоскости XZ рамки M (лицом к −Y рамки)."""
    for k in range(n):
        x0 = (k - (n - 1) / 2) * gap
        pts = [(x0 - w / 2 - slant, -h / 2), (x0 + w / 2 - slant, -h / 2), (x0 + w / 2 + slant, h / 2), (x0 - w / 2 + slant, h / 2)]
        acc.add(prism(pts, d), mat, M)


def ph2_pod(ch, s):
    """Наплечник: синий короб, толстый кремовый колпак-«шлем» (огибает верх, перёд/зад и внешний торец),
    косые красные решётки спереди/сзади/сбоку; внешний край заметно ниже."""
    C = V((s * 1.62, .05, 6.5)); Rp = Matrix.Translation(C) @ Matrix.Rotation(s * .48, 4, 'Y')
    ch.add(chunk((1.25, 1.5, .66), cut=.24), 'navy', Rp @ TRS((0, 0, -.08)))
    ch.add(chunk((1.0, 1.16, .22), cut=.3), 'dark', Rp @ TRS((s * .05, 0, -.46)))
    cap = [(-.52, -.48, .42), (.6, -.48, .42), (-.52, .48, .42), (.6, .48, .42),
           (-.62, -.84, .28), (.74, -.84, .28), (-.62, .84, .28), (.74, .84, .28),
           (-.6, -.92, .08), (.74, -.92, .06), (-.6, .92, .08), (.74, .92, .06),
           (.82, -.7, .1), (.82, .7, .1), (.8, 0, .02)]
    ch.add(hl(mir(cap, s)), 'cream', Rp)
    ch.add(hl(mir([(-.38, -.34, .5), (.36, -.34, .5), (-.38, .34, .5), (.36, .34, .5), (-.48, -.5, .4), (.46, -.5, .4), (-.48, .5, .4), (.46, .5, .4)], s)), 'cream', Rp)
    for sd in (-1, 1):
        Mv = Rp @ Matrix.Translation(V((-s * .05, sd * .78, -.14))) @ Matrix.Rotation(0 if sd < 0 else PI, 4, 'Z')
        ch.add(box(.92, .12, .3), 'dark', Mv)
        bars(ch, Mv @ TRS((0, -.07, 0)), 4, .1, .23, .2, .06 * s * (-sd))
        ch.add(box(1.0, .08, .05), 'gold', Mv @ TRS((0, -.05, -.22)))
    Mo = Rp @ Matrix.Translation(V((s * .66, 0, -.2))) @ Matrix.Rotation(s * PI / 2, 4, 'Z')
    ch.add(box(1.05, .1, .3), 'dark', Mo); bars(ch, Mo @ TRS((0, -.06, 0)), 4, .1, .22, .22, .05)
    ch.add(box(1.15, .08, .05), 'gold', Mo @ TRS((0, -.04, -.2)))
    # тёмный «сустав» между грудью и наплечником
    ch.add(chunk((.55, .9, .7), cut=.3), 'dark', TRS((s * 1.08, .05, 6.28)))


def ph2_hand(fist, s, W, E):
    """Кисть-«клешня»: тёмная ладонь, кремовая тыльная плита, 4 пальца по 3 фаланги с кремовыми накладками, большой палец, когти."""
    Hb = V((s * 2.2, -.76, 3.1))
    Md, Lh = seg_m(Hb, W, (s, 0, 0))
    fist.add(hl([(x * .36, y * .44, z) for x, y, z in ((-1, -1, .45), (1, -1, .45), (-1, 1, .45), (1, 1, .45), (-.9, -.9, -.2), (.95, -.95, -.2), (-.9, .9, -.2), (.95, .95, -.2))]), 'gun', Md)
    fist.add(hl([(.3, -.4, .42), (.48, -.4, .3), (.3, .42, .42), (.48, .42, .3), (.32, -.42, -.18), (.5, -.4, -.12), (.32, .42, -.18), (.5, .4, -.12)]), 'cream', Md)
    fist.add(box(.16, .9, .1), 'red', Md @ TRS((.42, 0, .5)))
    fist.add(box(.88, .98, .12), 'gold', Md @ TRS((0, 0, .58)))
    for k in range(4):
        y0 = (k - 1.5) * .21; p = V((.16, y0, -.22)); d = V((0, 0, -1)); pts = [p.copy()]
        for ln, cu in ((.3, .3), (.25, .8), (.2, 1.3)):
            d = (V((0, 0, -1)) * math.cos(cu) + V((-1, 0, 0)) * math.sin(cu)).normalized(); pts.append(pts[-1] + d * ln)
        for j in range(3):
            A_ = Md @ pts[j + 1]; B_ = Md @ pts[j]; r = .108 - j * .012
            vf, Mj = tbox(A_, B_, (r * .92, r * .92), (r, r), (s, 0, 0), cut=.3)
            fist.add(vf, 'gun', Mj)
            if j < 2:
                vf, Mj = tbox(A_, B_, (.05, r * 1.12), (.055, r * 1.15), (s, 0, 0), cut=.35)
                fist.add(vf, 'cream', Mj @ TRS((r + .02, 0, 0)))
        tip = Md @ pts[3]; dd = (Md.to_3x3() @ d).normalized()
        fist.add(cyl(.075, 0, .13, 5), 'gold', Matrix.Translation(tip + dd * .05) @ V((0, 0, 1)).rotation_difference(dd).to_matrix().to_4x4())
    T0 = V((-.05, -.42, .1)); T1 = T0 + V((-.14, -.2, -.2)); T2 = T1 + V((-.12, -.06, -.22))
    for a_, b_, r in ((T0, T1, .1), (T1, T2, .085)):
        vf, Mj = tbox(Md @ b_, Md @ a_, (r, r), (r, r), (s, 0, 0), cut=.3); fist.add(vf, 'gun', Mj)
    fist.add(chunk((.14, .2, .12), cut=.3), 'cream', Md @ Matrix.Translation(T0 + V((.03, -.04, 0))))


